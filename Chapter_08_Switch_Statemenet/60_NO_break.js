let day = 10;
// 1- monday , 2- tuesday, 3- wednesday, 4- thursday, 5- friday, 6- saturday, 7- sunday

switch (day) {
    case 1:
        console.log("Monday");
        
    case 2:
        console.log("Tuesday");
        
    case 3:
        console.log("Wednesday");
        
    case 4:
        console.log("Thursday");
        
    case 5:
        console.log("Friday");
        
    case 6:
        console.log("Saturday");
        
    case 7:
        console.log("Sunday");
        
    default:
        console.log("Invalid day");
}